export function Icon({
  name,
  size = 18,
  strokeWidth = 1.9,
  className,
}: {
  name: string | null | undefined;
  size?: number;
  strokeWidth?: number;
  className?: string;
}) {
  const Glyph = ICONS[name ?? ''] ?? CircleDashed;
  return <Glyph size={size} strokeWidth={strokeWidth} className={className} />;
}

